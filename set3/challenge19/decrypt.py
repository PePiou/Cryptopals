def encrypt():
    ciphers = CIPHERTEXT.split("\n")
    key = os.urandom(16)
    for i in range(len(ciphers)):
        ciphers[i] = CTR_encode(base64.b64decode(ciphers[i]), key)
    return ciphers

def rearange(ciphers: list[bytes]) -> list[bytes]:
    result = [b""] * 52
    for j in range(52):
        for i in range(len(ciphers)):
            if len(ciphers[i]) > j:
                result[j] += bytes([ciphers[i][j]])
    return result

def score(input_bytes: bytes, guess: int) -> float:
    score = 0
    for e in input_bytes:
        score += FREQUENCIES.get(chr(e ^ guess).lower(), 0)
    return score

def first_guess(input: list[bytes]) -> bytes:
    result = b""
    for e in input:
        s = 0
        index = 0
        for i in range(256):
            if score(e, i) > s:
                index = i
                s = score(e, i)
        result += bytes([index])
    return result

